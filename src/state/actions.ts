import { useLab, pushUndo } from './store';
import { getScene } from '../scenes';
import { runTask } from '../engine/client';
import { staticPose } from '../sensor/simulate';
import { PointCloud, attributesOf } from '../core/pointcloud';
import { downloadCloud, ExportFormat, loadFile } from '../io/load';
import { PRESETS, presetToConfig } from '../sensor/presets';

export const sceneOf = () => getScene(useLab.getState().sceneId);

export async function runScan(opts: { id?: string; name?: string; withCoverage?: boolean } = {}) {
  const s = useLab.getState();
  if (s.busy) return null;
  const scene = getScene(s.sceneId);
  s.patch({ busy: 'Scanning…' });
  try {
    const res = await runTask('scan', {
      scene, sensor: s.sensor, trajectory: staticPose(s.pose.x, s.pose.y, s.pose.z, s.pose.yaw, s.pose.pitch), sweeps: s.scanOpts.sweeps, seed: s.scanOpts.seed,
      maxRays: s.scanOpts.maxRays, distortion: false, scanId: 0, wantViz: true, name: opts.name ?? `Scan · ${s.sensor.name}`,
    });
    const st = useLab.getState();
    st.setCloud(opts.id ?? 'scan', res.cloud);
    st.patch({ scanInfo: { stats: res.stats, viz: res.viz, coverage: null }, picks: [] });
    if (res.stats.reduced) st.notify(`Point budget reached — angular resolution thinned to ${res.stats.effectiveHRes.toFixed(2)}°.`, 'warn');
    if (opts.withCoverage !== false) void computeScanCoverage();
    return res;
  } catch (e) {
    useLab.getState().notify(`Scan failed: ${(e as Error).message}`, 'error');
    return null;
  } finally {
    useLab.getState().patch({ busy: null });
  }
}

export async function computeScanCoverage(radius = 0.12) {
  const s = useLab.getState();
  const c = s.clouds['scan'];
  if (!c) return;
  const r = await runTask('coverage', { scene: getScene(s.sceneId), clouds: [{ positions: c.positions, count: c.count }], radius, pose: { x: s.pose.x, y: s.pose.y, z: s.pose.z, yaw: s.pose.yaw }, sensor: s.sensor });
  const missing: number[] = [];
  for (let i = 0; i < r.samples.count; i++) if (!r.union[i]) missing.push(r.samples.pos[i * 3], r.samples.pos[i * 3 + 1], r.samples.pos[i * 3 + 2]);
  const cur = useLab.getState().scanInfo;
  if (cur) useLab.setState({ scanInfo: { ...cur, coverage: { total: r.total, covered: r.covered, coveredPct: (100 * r.covered) / r.total, area: r.area, coveredArea: r.coveredArea, vis: r.vis, missingPositions: Float32Array.from(missing) } } });
}

export async function exampleCloud(kind: 'A' | 'B' | 'C') {
  const s = useLab.getState();
  s.patch({ busy: 'Generating example…' });
  const scene = getScene(kind);
  const tls = PRESETS.find((p) => p.id === 'tls')!;
  const cfg = { ...presetToConfig(tls), hRes: 0.5, channels: 80 };
  const res = await runTask('scan', { scene, sensor: cfg, trajectory: staticPose(scene.defaultPose.x, scene.defaultPose.y, scene.defaultPose.z, scene.defaultPose.yaw), sweeps: 1, seed: 1, maxRays: 120000, distortion: false, scanId: 0, name: `Example · ${scene.name} (TLS-like)` });
  res.cloud.meta = { ...res.cloud.meta, description: 'Bundled procedural example: generated by this app’s simulator (synthetic, not measured data).', license: 'Generated by this project (MIT)' };
  const st = useLab.getState();
  if (st.sceneId !== kind) st.setScene(kind);
  useLab.getState().setCloud('explorer', res.cloud);
  useLab.getState().patch({ busy: null });
  return res.cloud;
}

export async function uploadCloud(file: File, kind: 'measured' | 'simulated' = 'measured') {
  const s = useLab.getState();
  try {
    s.patch({ busy: `Loading ${file.name}…` });
    const c = await loadFile(file);
    c.meta.kind = kind;
    useLab.getState().setCloud('explorer', c);
    useLab.getState().notify(`Loaded ${file.name}: ${c.count.toLocaleString()} points (${attributesOf(c).join(', ')}).`, 'ok');
    return c;
  } catch (e) {
    useLab.getState().notify((e as Error).message, 'error');
    return null;
  } finally {
    useLab.getState().patch({ busy: null });
  }
}

export function exportCloudFile(c: PointCloud, fmt: ExportFormat) {
  const name = downloadCloud(c, fmt);
  const s = useLab.getState();
  s.patch({ exportsLog: [...s.exportsLog, { name, fmt, count: c.count }] });
  s.notify(`Exported ${name} (${c.count.toLocaleString()} points; ${attributesOf(c).join(', ')}).`, 'ok');
}

export function takeScreenshot() {
  const cv = document.querySelector('canvas');
  if (!cv) return;
  cv.toBlob((b) => {
    if (!b) return;
    const a = document.createElement('a');
    a.href = URL.createObjectURL(b);
    a.download = `lidar-lab-${Date.now()}.png`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 2000);
  });
}

export const activeCloud = (): PointCloud | null => {
  const s = useLab.getState();
  return (s.activeCloudId && s.clouds[s.activeCloudId]) || Object.values(s.clouds)[0] || null;
};

export function clearPicks() {
  const prev = useLab.getState().picks;
  if (!prev.length) return;
  useLab.setState({ picks: [] });
  pushUndo('clear picks', () => useLab.setState({ picks: prev }));
}
